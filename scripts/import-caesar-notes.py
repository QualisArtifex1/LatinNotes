#!/usr/bin/env python3
"""Import only Dickinson's Notes fields. Requires beautifulsoup4 and curl.

Run: python scripts/import-caesar-notes.py [--source-dir cached-html-directory]
Source files in a cache directory are named 1.html through 7.html.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
from subprocess import check_output
from bs4 import BeautifulSoup

ROOT = Path(__file__).resolve().parents[1]
BASE = 'https://dcc.dickinson.edu/caesar/book-1/chapter-1-'
# Source headings are preserved in the displayed note. Only matching metadata
# may use an inflected form or omit a supplied word/abbreviation.
ANCHORS = {
    (1, 4): ['Belgae', 'Aquitani', 'Celtae'],
    (1, 6): ['Garumna flumen', 'Matrona', 'Sequana'],
    (1, 20): ['in septentrionem…solem'],
    (1, 21): ['spectat inter occasum solis et septentriones'],
    (2, 3): ['M. Messala', 'M. Pisone consulibus'],
    (5, 4): ['praeter quod'],
    (5, 11): ['receptos ad se socios sibi adsciscunt'],
    (6, 16): ['Pisone'],
    (6, 17): ['Gabinio'],
}

def normalize_space(text):
    return re.sub(r'\s+', ' ', text).strip()

def extract(chapter, raw):
    soup = BeautifulSoup(raw, 'html.parser')
    field = soup.select_one('.field--name-field-notes')
    if field is None:
        raise ValueError(f'No Notes field in chapter 1.{chapter}')
    paragraphs = field.find_all('p')
    notes, source_texts = [], []
    for index, paragraph in enumerate(paragraphs, 1):
        original = normalize_space(paragraph.get_text())
        if not original:
            continue
        source_texts.append(original)
        # Keep inline emphasis and every word; remove links, site formatting,
        # scripts and all attributes. No vocabulary or media fields are read.
        clean = BeautifulSoup(str(paragraph), 'html.parser')
        for tag in list(clean.find_all()):
            if tag.name in ['script', 'style']:
                tag.decompose()
            elif tag.name in ['p', 'strong', 'em', 'b', 'i', 'br', 'sup', 'sub']:
                tag.attrs = {}
            else:
                tag.unwrap()
        if normalize_space(clean.get_text()) != original:
            raise ValueError(f'Changed note text: 1.{chapter}, paragraph {index}')
        lead = normalize_space(paragraph.get_text().split(':', 1)[0])
        phrases = ANCHORS.get((chapter, index), [] if index == 1 else [lead])
        notes.append({
            'id': f'caesar-1-{chapter}-note-{index:02}',
            'label': 'Overview' if index == 1 else f'Chapter 1.{chapter}',
            'reading': f'De Bello Gallico, 1.{chapter}',
            'line': '',
            'commentHtml': str(clean.p),
            'anchorPhrases': phrases,
        })
    return {
        'key': f'De Bello Gallico, 1.{chapter}',
        'title': f'Caesar, De Bello Gallico 1.{chapter}',
        'sections': [f'Chapter 1.{chapter}'],
        'credit': 'Caesar notes: Dickinson College Commentaries, edited by Christopher Francese. CC BY-SA.',
        'sourceCitation': 'Christopher Francese, Caesar: Selections from the Gallic War. Carlisle, Pennsylvania: Dickinson College Commentaries, 2011, revised and enlarged 2018. Original commentators credited in each note. Reused under the same Creative Commons Attribution-ShareAlike terms.',
        'sourceUrl': BASE + str(chapter),
        'sourceTermsUrl': 'https://dcc.dickinson.edu/terms-use',
        'sourceNotesSha256': hashlib.sha256('\n'.join(source_texts).encode()).hexdigest(),
        'notes': notes,
    }

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path)
    args = parser.parse_args()
    entries = {}
    for chapter in range(1, 8):
        raw = (args.source_dir / f'{chapter}.html').read_bytes() if args.source_dir else check_output(['curl', '-fsSL', '--max-time', '30', BASE + str(chapter)])
        entry = extract(chapter, raw)
        entries[entry['key']] = entry
    header = '// Dickinson College Commentaries, Caesar 1.1–1.7, Notes only. CC BY-SA.\n// Generated by scripts/import-caesar-notes.py; links removed, wording preserved.\n'
    (ROOT / 'caesar-commentary.js').write_text(header + 'window.LATIN_CAESAR_COMMENTARY = ' + json.dumps(entries, ensure_ascii=False, indent=2) + ';\n')
    print({key: len(entry['notes']) for key, entry in entries.items()})

if __name__ == '__main__':
    main()
