import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('../editor-history.js',import.meta.url),'utf8');
const {EditorHistory}=await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const base={words:[],lines:[],translation:'',notes:'',fontSize:30,lineSpacing:48};
const history=new EditorHistory(3);
history.record(base);
const connected={...base,lines:[{id:'a'}]};history.record(connected);
assert.equal(history.undo(),base);assert.equal(history.redo(),connected);
history.undo();history.record({...base,words:[{id:'word',highlight:'red'}]});
assert.equal(history.redo(),null,'A new edit clears redo');
history.reset(base);
history.record({...base,translation:'a'},1000);
history.record({...base,translation:'ab'},1100);
assert.equal(history.past.length,1,'Group continuous typing');
assert.equal(history.undo(),base);
history.redo();history.record({...base,translation:'abc'},2000);
assert.equal(history.past.length,2,'A pause starts a new typing step');
for(let n=0;n<10;n++)history.record({...base,fontSize:n});
assert.equal(history.past.length,3,'History is bounded');
history.reset(base);assert.equal(history.undo(),null);assert.equal(history.redo(),null);
console.log('PASS: undo/redo, branching, typing groups, capacity, document reset.');
