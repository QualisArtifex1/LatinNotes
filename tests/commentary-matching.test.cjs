const assert=require('node:assert/strict');
const m=require('../commentary-matching.js');
const words=text=>text.split(' ').map(text=>({key:m.normalize(text),lineNumber:1}));
const note=html=>[{id:'n',line:'1',commentHtml:html}];
let r=m.attach(note('<strong>(puerum) cubantem</strong>: boy; <strong>quā vēnerant</strong>: where'),words('duo cubantemque detonderunt et qua venerant recesserunt'));
assert(r.assignments[1].has('n'));assert(r.assignments[4].has('n'));assert(r.assignments[5].has('n'));assert(!r.assignments[2].size);
r=m.attach(note('<strong>parva…corpora</strong>'),words('parva duorum corpora'));
assert(r.assignments.every(a=>a.has('n')),'Ellipsis includes intervening words');
r=m.attach(note('<strong>quī prīmus…vēnit</strong>'),[{key:'qui',lineNumber:1},{key:'primus',lineNumber:1},{key:'fato',lineNumber:2},{key:'venit',lineNumber:2}],true);
assert(r.assignments.every(a=>a.has('n')),'Verse-spanning phrase');
assert(m.matches('seque','se'));assert(!m.matches('atque','at'),'Never strip particles from unrelated short roots');
assert.deepEqual(m.tokens('Ō…Tȳdīdē'),['o','tydide']);
assert.deepEqual(m.tokens('tenuē(runt)'),['tenuere']);
r=m.attach(note('<strong>nōn illiterātus</strong>'),words('non illitteratus'));assert(r.assignments.every(a=>a.has('n')));
r=m.attach(note('<strong>amō</strong>'),words('amor'));assert(!r.assignments[0].size,'No arbitrary prefix matching');
const audit=require('../commentary-audit.json');
assert.equal(audit.filter(r=>r.status==='unmatched').length,2);
assert(audit.filter(r=>r.status==='unmatched').every(r=>r.lesson===47&&['lūce','custōs'].includes(r.phrase)));
for(const phrase of ['lūce','custōs'])assert(audit.some(r=>r.lesson===48&&r.phrase===phrase&&r.status.startsWith('matched')));
assert(audit.some(r=>r.phrase==='(puerum) cubantem'&&r.attachedWords.includes('cubantemque')));
console.log('PASS: enclitics, every bold phrase, span selection, diacritics, explicit variants, and full audit exceptions.');
